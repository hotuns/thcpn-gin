import { act } from "react";
import { expect, it, vi } from "vitest";
import { api, type DataStream, type DeviceMapItem } from "@thcpn/api";
import { EcoDeviceInspector } from "../../apps/platform/src/features/atlas/eco-device";
import { render, eventually } from "../render";
vi.mock("@thcpn/auth", () => ({ useAuth: () => ({ user: { id: "observer" } }) }));
const stamp = "2026-11-03T00:00:00Z";
const metrics: DataStream[] = Array.from({ length: 6 }, (_, index) => ({ id: `stream${index}`, name: `指标${index}`, unit: index === 0 ? "°C" : "%", code: `metric${index}`, type: "telemetry", status: "active", device_id: "station", computed: false, created_by: "observer", created_at: stamp, updated_at: stamp }));
const device: DeviceMapItem = { device_id: "station", name: "青山标准站", serial_no: "ST001", device_type: "station", status: "active", location_source: "none", child_count: 0, environment: { observation_objects: [], purposes: [], research_tags: [] } };
it("renders compact metric rows and pages every chosen metric through one shared plot", async () => {
  vi.spyOn(api.dataStreams, "list").mockResolvedValue({ items: metrics });
  vi.spyOn(api.telemetry, "dataStream").mockResolvedValue({ device_id: "station", start_time: stamp, end_time: stamp, limit: 1, series: [] });
  const { host } = await render(<EcoDeviceInspector device={device} workspaceId="forest" config={{ trend_hours: 24, layout: "balanced", presentation: "deep-blue", show_trends: true, show_images: false, metric_defaults: { "device:station": metrics.map(item => item.code) } }} />);
  await eventually(() => expect(host.querySelectorAll(".eco-observation-row")).toHaveLength(6));
  expect(host.querySelectorAll(".eco-trend-viewer")).toHaveLength(1);
  await eventually(() => expect(api.telemetry.dataStream).toHaveBeenCalledTimes(6));
  expect(vi.mocked(api.telemetry.dataStream).mock.calls.map(call => call[0]).sort()).toEqual(metrics.map(stream => stream.id).sort());
  expect(host.querySelector(".eco-trend-viewer .eco-section-heading > span")?.textContent).toBe("°C");
  expect(host.querySelector<HTMLButtonElement>('[aria-label="上一指标"]')?.disabled).toBe(true);
  expect(host.querySelector(".eco-reading-grid")).toBeNull();
  const plot = host.querySelector(".eco-trend-plot");
  await act(async () => host.querySelectorAll<HTMLButtonElement>(".eco-observation-row")[5].click());
  expect(host.querySelector<HTMLSelectElement>('select[aria-label="趋势指标"]')?.value).toBe("stream5");
  expect(host.querySelector(".eco-trend-pager span")?.textContent).toBe("6 / 6");
  expect(host.querySelector(".eco-trend-viewer .eco-section-heading > span")?.textContent).toBe("%");
  expect(host.querySelector<HTMLButtonElement>('[aria-label="下一指标"]')?.disabled).toBe(true);
  await act(async () => host.querySelector<HTMLButtonElement>('[aria-label="上一指标"]')!.click());
  expect(host.querySelector(".eco-trend-pager span")?.textContent).toBe("5 / 6");
  await act(async () => host.querySelector<HTMLButtonElement>('[aria-label="下一指标"]')!.click());
  expect(host.querySelector(".eco-trend-pager span")?.textContent).toBe("6 / 6");
  expect(host.querySelector(".eco-trend-plot")).toBe(plot);
  expect(host.querySelector(".eco-panel-title")?.textContent).toBe("设备采集数据");
  expect(host.querySelector('[class*="atlas-"]')).toBeNull();
  expect(host.textContent).not.toContain("采样");
  expect(host.textContent).not.toContain("平均");
  expect(host.querySelectorAll(".eco-time-pills button")).toHaveLength(3);
});

it("keeps the two-photo overview and opens a full gallery with collected/asset tabs", async () => {
  vi.spyOn(api.dataStreams, "list").mockResolvedValue({ items: [] });
  const images = vi.spyOn(api.media, "images").mockResolvedValue({ items: [{ id: "photo", device_id: "station", data_stream_id: "camera", captured_at: stamp, media_type: "image", preview_url: "/photo.jpg", thumbnail_url: "/thumb.jpg", download_allowed: false, delete_allowed: false }], total: 1, page: 1, page_size: 2 });
  vi.spyOn(api.devices, "profile").mockResolvedValue({ device_id: "station", location_source: "none", images: [], can_configure: false, can_manage_placement: false });
  const { host } = await render(<EcoDeviceInspector device={device} workspaceId="forest" config={{ trend_hours: 24, layout: "balanced", presentation: "deep-blue", show_trends: false, show_images: true }} />);
  await eventually(() => expect(host.querySelectorAll(".eco-photo")).toHaveLength(1));
  const overview = host.querySelector<HTMLElement>(".eco-imagery")!;
  expect(overview.querySelector(".eco-section-heading h3")?.textContent).toBe("采集图片");
  expect(overview.textContent).not.toContain("资产照片");
  await act(async () => overview.querySelector<HTMLButtonElement>(".eco-section-heading button")!.click());
  const gallery = document.querySelector<HTMLElement>(".eco-gallery")!;
  expect(gallery).toBeTruthy();
  expect(gallery.querySelector("[aria-pressed=true]")?.textContent).toBe("采集图片");
  expect(gallery.textContent).toContain("资产照片");
  await eventually(() => expect(images).toHaveBeenCalledWith("station", expect.objectContaining({ page_size: 12 })));
  await act(async () => [...gallery.querySelectorAll<HTMLButtonElement>("button")].find(button => button.textContent === "资产照片")!.click());
  expect(gallery.querySelector("[aria-pressed=true]")?.textContent).toBe("资产照片");
});
